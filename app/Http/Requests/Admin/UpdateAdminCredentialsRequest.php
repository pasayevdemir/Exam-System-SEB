namespace App\Http\Requests\Admin;

use Illuminate\Foundation\Http\FormRequest;

class UpdateAdminCredentialsRequest extends FormRequest
{
    /**
     * The admin panel is gated by AdminMiddleware and the student pages by
     * StudentMiddleware, so by the time a request class runs the caller is
     * already the right kind of user.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'current_password' => ['required', 'string'],
            'username' => ['required', 'string', 'max:255'],
            // Nullable so the username can be corrected on its own. Longer than
            // the students' min:8 because this one credential authorises every
            // destructive action in the system.
            'password' => ['nullable', 'string', 'min:12', 'confirmed'],
        ];
    }
}
